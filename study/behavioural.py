"""Behavioural suite for negation, contrast, sarcasm and intensity: construction and evaluation.

    python -m study.behavioural build      # writes behavioural/suite_v1.jsonl and annotation_queue_v1.csv
    python -m study.behavioural evaluate   # scores the frozen candidates; writes results/behavioural/

Construction. Every case comes from a template in TEMPLATES with explicit slot fillers, so the suite is
regenerated byte for byte by this script. Two test types:
  minimal_pair      two texts that differ in one construction (e.g. "was" vs "was not"); each member
                    carries its own expected label; a pair passes only if both members are labelled correctly.
  label_preserving  a set of texts that should all receive one label (e.g. intensity variants); the set
                    passes only if every member is labelled correctly.
Labels are proposals by the template author (an AI assistant), not human judgements. Every case starts
as "unadjudicated"; results stay provisional and outside headline claims until a person adjudicates
them through behavioural/annotation_queue_v1.csv.

Splits. Families sharing a template group are assigned together: per phenomenon, template groups are
shuffled (seed 42) and alternately assigned to "dev" and "heldout". Evaluation reports held-out
families; dev families may be used to develop prompts for the LLM baseline.

Uncertainty. Cases within a family are dependent, so intervals come from a family-level bootstrap
(families resampled with replacement within each phenomenon; 10,000 replicates; percentile 95%).
"""
import argparse
import hashlib
import itertools
import json
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
SUITE = ROOT / "behavioural" / "suite_v1.jsonl"
QUEUE = ROOT / "behavioural" / "annotation_queue_v1.csv"
ADJUDICATIONS = ROOT / "behavioural" / "adjudications_v1.csv"  # private, gitignored; applied if present
OUT = ROOT / "results" / "behavioural"
GENERATOR = {"script": "study/behavioural.py", "version": "1"}
LABEL_SOURCE = "proposed by the template author (an AI assistant); not human-validated"
SEED, N_BOOT = 42, 10_000

SUBJECTS = ["The movie", "This film", "The story", "The acting"]
POS_ADJ = ["good", "great", "enjoyable", "wonderful"]
NEG_ADJ = ["bad", "boring", "dull", "disappointing"]
ASPECTS = ["acting", "soundtrack", "camera work"]


def _p(label: str) -> str:
    return {"pos": "positive", "neg": "negative"}[label]


SLUG = {"The movie": "movie", "This film": "film", "The story": "story", "The acting": "acting"}


# Each template yields (family suffix, unit suffix, test type, [(text, expected, role)], ambiguity, rationale, slots).
# A family groups paraphrases of one item (e.g. one adjective under several subjects); a unit is one test:
# a minimal pair, a label-preserving set, or a single case.
def negation_copula():
    for adj, subj in itertools.product(POS_ADJ, SUBJECTS):
        yield (adj, SLUG[subj], "minimal_pair", [(f"{subj} was {adj}.", "pos", "base"), (f"{subj} was not {adj}.", "neg", "variant")],
               "low", "Negating a positive predicate reverses the evaluation.", {"subject": subj, "adjective": adj})


def negation_copula_negative_adjective():
    for adj, subj in itertools.product(NEG_ADJ[:3], SUBJECTS):
        yield (adj, SLUG[subj], "minimal_pair", [(f"{subj} was {adj}.", "neg", "base"), (f"{subj} was not {adj}.", "pos", "variant")],
               "medium", "Negating a negative predicate removes the criticism; the result is weakly positive, not strong praise.",
               {"subject": subj, "adjective": adj})


def negation_contraction():
    for adj, subj in itertools.product(POS_ADJ, SUBJECTS):
        yield (adj, SLUG[subj], "minimal_pair", [(f"{subj} is {adj}.", "pos", "base"), (f"{subj} isn't {adj}.", "neg", "variant")],
               "low", "The contracted negation n't reverses a positive predicate.", {"subject": subj, "adjective": adj})


def negation_verb():
    verbs = [("enjoyed", "enjoy"), ("liked", "like"), ("loved", "love")]
    forms = [("did not", "this film", "didnot"), ("didn't", "the movie", "didnt")]
    for (past, base), (form, obj, tag) in itertools.product(verbs, forms):
        yield (base, tag, "minimal_pair", [(f"I {past} {obj}.", "pos", "base"), (f"I {form} {base} {obj}.", "neg", "variant")],
               "low", "Negating a verb of liking reverses the reviewer's stance.", {"verb": base, "negation": form})


def negation_never():
    pairs = [("I would watch it again.", "I would never watch it again."),
             ("I will recommend it to my friends.", "I will never recommend it to my friends."),
             ("I want to see it again.", "I never want to see it again.")]
    for i, (base, variant) in enumerate(pairs):
        yield (f"p{i}", "u0", "minimal_pair", [(base, "pos", "base"), (variant, "neg", "variant")], "low",
               "'Never' negates the intention to rewatch or recommend.", {"base": base})


def negation_quantifier():
    pairs = [("The film has many redeeming qualities.", "The film has no redeeming qualities."),
             ("There was plenty of tension in every scene.", "There was no tension in any scene."),
             ("Every joke landed.", "Not a single joke landed.")]
    for i, (base, variant) in enumerate(pairs):
        yield (f"p{i}", "u0", "minimal_pair", [(base, "pos", "base"), (variant, "neg", "variant")], "low",
               "A negative quantifier denies the positive property.", {"base": base})


def _singles(texts, label, ambiguity, rationale):
    for i, text in enumerate(texts):
        yield ("set", f"s{i}", "single", [(text, label, "single")], ambiguity, rationale, {})


def negation_litotes():
    yield from _singles(["Not bad at all.", "Honestly, it was not bad at all.", "The film is not without its charms.",
                         "I can't say I didn't enjoy it."], "pos", "high",
                        "Litotes and double negation assert a mild positive; readers may disagree on strength or polarity.")


def contrast_but():
    for aspect, (pos, neg) in itertools.product(ASPECTS, [("great", "dull"), ("excellent", "tedious"), ("superb", "boring")]):
        yield (aspect.replace(" ", ""), pos, "minimal_pair",
               [(f"The {aspect} was {pos}, but overall the film was {neg}.", "neg", "base"),
                (f"The {aspect} was {neg}, but overall the film was {pos}.", "pos", "variant")],
               "low", "The clause after 'but' states the overall verdict and outweighs the conceded aspect.",
               {"aspect": aspect, "positive": pos, "negative": neg})


def contrast_although():
    for aspect, (love, hate) in itertools.product(ASPECTS, [("loved", "hated"), ("enjoyed", "disliked")]):
        yield (aspect.replace(" ", ""), love, "minimal_pair",
               [(f"Although the {aspect} was weak, I {love} the film.", "pos", "base"),
                (f"Although the {aspect} was strong, I {hate} the film.", "neg", "variant")],
               "low", "The main clause carries the verdict; the concessive clause is subordinate.",
               {"aspect": aspect, "verbs": [love, hate]})


def contrast_however():
    for aspect, (like, dislike) in itertools.product(ASPECTS, [("enjoyed", "disliked"), ("admired", "resented")]):
        yield (aspect.replace(" ", ""), like, "minimal_pair",
               [(f"The {aspect} was weak. However, I {like} the film as a whole.", "pos", "base"),
                (f"The {aspect} was strong. However, I {dislike} the film as a whole.", "neg", "variant")],
               "low", "The sentence after 'However' gives the overall verdict.", {"aspect": aspect, "verbs": [like, dislike]})


def contrast_expectation():
    pairs = [("I expected to hate it, but it was wonderful.", "pos"), ("I expected to love it, but it was awful.", "neg"),
             ("I went in with low expectations and came out delighted.", "pos"),
             ("I went in with high expectations and came out disappointed.", "neg")]
    for i in (0, 2):
        yield (f"p{i // 2}", "u0", "minimal_pair", [(pairs[i][0], pairs[i][1], "base"), (pairs[i + 1][0], pairs[i + 1][1], "variant")],
               "low", "The outcome clause, not the stated expectation, carries the verdict.", {})


def sarcasm_followup():
    praises = ["What a masterpiece.", "Brilliant, just brilliant.", "Truly a triumph of cinema."]
    followups = [("I was moved to tears.", "I fell asleep twice."),
                 ("I would happily watch it again.", "I checked my watch every five minutes.")]
    for (i, praise), (j, (sincere, sarcastic)) in itertools.product(enumerate(praises), enumerate(followups)):
        yield (f"p{i}", f"f{j}", "minimal_pair", [(f"{praise} {sincere}", "pos", "base"), (f"{praise} {sarcastic}", "neg", "variant")],
               "medium", "Identical praise; a follow-up describing boredom marks the praise as sarcastic.",
               {"praise": praise, "sincere": sincere, "sarcastic": sarcastic})


def sarcasm_standalone():
    yield from _singles(["Oh great, another two hours of my life I will never get back.",
                         "If you enjoy watching paint dry, this is the film for you.",
                         "Wonderful, the ending was exactly as predictable as the trailer promised.",
                         "Thanks to this film, I finally caught up on my sleep."], "neg", "medium",
                        "Surface praise words in an ironic frame; the described experience is negative.")


def sarcasm_backhanded():
    yield from _singles(["The best part was when the credits rolled.",
                         "A perfect film, if you are looking for a cure for insomnia.",
                         "Five stars for the popcorn; none for the film.",
                         "The most exciting moment was finding the exit."], "neg", "medium",
                        "Praise is directed at something other than the film, which implies the film itself is poor.")


def sarcasm_rhetorical():
    yield from _singles(["Who needs a coherent plot when you have explosions?",
                         "Did anyone read this script before filming it?",
                         "Why sit through two hours of this when the trailer shows everything?",
                         "What could possibly go wrong with a script this lazy?"], "neg", "medium",
                        "A rhetorical question that presupposes a flaw in the film.")


def intensity_degree():
    degrees = ["slightly", "somewhat", "quite", "very", "extremely"]
    for adj, label in [("enjoyable", "pos"), ("entertaining", "pos"), ("boring", "neg"), ("disappointing", "neg")]:
        yield (adj, "u0", "label_preserving", [(f"The film was {d} {adj}.", label, d) for d in degrees], "low",
               "Degree modifiers change intensity, not polarity.", {"adjective": adj, "degrees": degrees})


def intensity_emphasis():
    for adj, label in [("good", "pos"), ("great", "pos"), ("bad", "neg"), ("awful", "neg")]:
        texts = [f"It was {adj}.", f"It was {adj}!!!", f"It was {adj}, truly {adj}.", f"IT WAS {adj.upper()}."]
        yield (adj, "u0", "label_preserving", [(t, label, f"m{i}") for i, t in enumerate(texts)], "low",
               "Repetition, punctuation and capitals add emphasis without changing polarity.", {"adjective": adj})


def intensity_mitigated():
    for adj in ["disappointing", "boring", "dull"]:
        texts = [f"It was a bit {adj}.", f"It was a little {adj}.", f"It was mildly {adj}."]
        yield (adj, "u0", "label_preserving", [(t, "neg", f"m{i}") for i, t in enumerate(texts)], "medium",
               "Mitigated criticism is still criticism; the overall stance is mildly negative.", {"adjective": adj})


def intensity_superlative():
    for word, label in [("best", "pos"), ("worst", "neg")]:
        texts = [f"It was one of the {word} films of the year.", f"It is the {word} film I have seen in years.",
                 f"Easily the {word} film of the decade."]
        yield (word, "u0", "label_preserving", [(t, label, f"m{i}") for i, t in enumerate(texts)], "low",
               "Superlatives intensify a judgement whose polarity the superlative itself states.", {"superlative": word})


TEMPLATES = {  # family prefix -> (phenomenon, template group, generator)
    "neg-copula-pos": ("negation", "copula", negation_copula),
    "neg-copula-neg": ("negation", "copula", negation_copula_negative_adjective),
    "neg-contraction": ("negation", "contraction", negation_contraction),
    "neg-verb": ("negation", "verb", negation_verb),
    "neg-never": ("negation", "never", negation_never),
    "neg-quantifier": ("negation", "quantifier", negation_quantifier),
    "neg-litotes": ("negation", "litotes", negation_litotes),
    "con-but": ("contrast", "but", contrast_but),
    "con-although": ("contrast", "although", contrast_although),
    "con-however": ("contrast", "however", contrast_however),
    "con-expectation": ("contrast", "expectation", contrast_expectation),
    "sar-followup": ("sarcasm", "followup", sarcasm_followup),
    "sar-standalone": ("sarcasm", "standalone", sarcasm_standalone),
    "sar-backhanded": ("sarcasm", "backhanded", sarcasm_backhanded),
    "sar-rhetorical": ("sarcasm", "rhetorical", sarcasm_rhetorical),
    "int-degree": ("intensity", "degree", intensity_degree),
    "int-emphasis": ("intensity", "emphasis", intensity_emphasis),
    "int-mitigated": ("intensity", "mitigated", intensity_mitigated),
    "int-superlative": ("intensity", "superlative", intensity_superlative),
}


def build_cases() -> list[dict]:
    rng = np.random.default_rng(SEED)
    split = {}
    for phenomenon in sorted({ph for ph, _, _ in TEMPLATES.values()}):
        names = sorted({f"{ph}/{grp}" for ph, grp, _ in TEMPLATES.values() if ph == phenomenon})
        for i, group in enumerate(rng.permutation(names)):
            split[group] = "dev" if i % 2 == 0 else "heldout"
    cases = []
    for prefix, (phenomenon, group, generator) in TEMPLATES.items():
        for family_suffix, unit_suffix, test_type, members, ambiguity, rationale, slots in generator():
            family = f"{prefix}-{family_suffix}"
            unit = f"{family}-{unit_suffix}"
            for k, (text, expected, role) in enumerate(members):
                cases.append({"case_id": f"{unit}-{k}", "unit_id": unit, "family_id": family,
                              "template_group": f"{phenomenon}/{group}", "phenomenon": phenomenon,
                              "test_type": test_type, "role": role, "text": text, "expected_label": _p(expected),
                              "rationale": rationale, "ambiguity": ambiguity,
                              "construction": {"method": "template", "template": prefix, "slots": slots, **GENERATOR},
                              "label_source": LABEL_SOURCE, "adjudication_status": "unadjudicated",
                              "split": split[f"{phenomenon}/{group}"]})
    ids, seen, duplicates = [c["case_id"] for c in cases], set(), set()
    for case in cases:
        (duplicates if case["text"] in seen else seen).add(case["text"])
    if duplicates or len(set(ids)) != len(ids):
        raise SystemExit(f"duplicate texts or case ids in the suite: {sorted(duplicates)}")
    return cases


def build() -> None:
    cases = build_cases()
    SUITE.parent.mkdir(exist_ok=True)
    with open(SUITE, "w", encoding="utf-8", newline="\n") as handle:
        for case in cases:
            handle.write(json.dumps(case, ensure_ascii=False, sort_keys=True) + "\n")
    queue = pd.DataFrame([{"case_id": c["case_id"], "family_id": c["family_id"], "phenomenon": c["phenomenon"],
                           "split": c["split"], "ambiguity": c["ambiguity"], "text": c["text"],
                           "proposed_label": c["expected_label"], "rationale": c["rationale"]} for c in cases])
    for column in ("decision", "adjudicated_label", "annotator", "notes", "reviewed_utc"):
        queue[column] = ""
    queue.to_csv(QUEUE, index=False, lineterminator="\n")
    df = pd.DataFrame(cases)
    print(df.groupby(["phenomenon", "split"]).agg(families=("family_id", "nunique"), cases=("case_id", "size")))
    print(f"wrote {SUITE.relative_to(ROOT)} ({len(cases)} cases, sha256 "
          f"{hashlib.sha256(SUITE.read_bytes()).hexdigest()[:12]}) and {QUEUE.relative_to(ROOT)}")


def load_suite() -> pd.DataFrame:
    df = pd.read_json(SUITE, lines=True)
    if ADJUDICATIONS.exists():  # a person's decisions override proposals and change the status
        adj = pd.read_csv(ADJUDICATIONS, keep_default_na=False)
        adj = adj[adj["decision"].isin(["accept", "relabel", "exclude"])].set_index("case_id")
        for cid, row in adj.iterrows():
            i = df.index[df["case_id"] == cid]
            df.loc[i, "adjudication_status"] = "excluded" if row["decision"] == "exclude" else "adjudicated"
            if row["decision"] == "relabel":
                df.loc[i, "expected_label"] = row["adjudicated_label"]
    return df


def unit_outcomes(df: pd.DataFrame, pred: np.ndarray) -> pd.DataFrame:
    """One row per test unit (minimal pair, label-preserving set or single case): passes if every member is correct."""
    df = df.assign(correct=(pred == (df["expected_label"] == "positive").astype(int)))
    units = df.groupby("unit_id").agg(family_id=("family_id", "first"), phenomenon=("phenomenon", "first"),
                                      test_type=("test_type", "first"), split=("split", "first"),
                                      ambiguity=("ambiguity", "first"), members=("case_id", "size"),
                                      members_correct=("correct", "sum"))
    units["passed"] = units["members_correct"] == units["members"]
    return units.reset_index()


def family_bootstrap(units: pd.DataFrame, value: str, rng: np.random.Generator) -> tuple[float, float]:
    fam = units.groupby("family_id")[value].agg(["sum", "size"])
    sums, sizes = fam["sum"].to_numpy(float), fam["size"].to_numpy(float)
    draws = rng.integers(0, len(fam), size=(N_BOOT, len(fam)))
    reps = sums[draws].sum(axis=1) / sizes[draws].sum(axis=1)
    return float(np.quantile(reps, 0.025)), float(np.quantile(reps, 0.975))


def evaluate() -> None:
    from src.pipeline import labels_from_scores, load_artefact  # imported here so `build` needs no models

    proto = json.loads((ROOT / "protocol" / "protocol_v1.json").read_text(encoding="utf-8"))
    suite = load_suite()
    suite = suite[suite["adjudication_status"] != "excluded"].reset_index(drop=True)
    rows, case_rows = [], []
    for cid, spec in proto["candidates"].items():
        if spec["config"] is None:
            fit = json.loads((ROOT / "results" / "study" / "fits" / f"{cid}.json").read_text(encoding="utf-8"))
            pred, scores, zero = np.full(len(suite), fit["majority_class"]), np.full(len(suite), np.nan), 0
        else:
            base = "models/artefacts" if cid == "svc_uni_8k_historical" else "models/study/artefacts"
            pipeline, _ = load_artefact(ROOT / base / spec["model_version"])
            x = pipeline[:-1].transform(suite["text"].tolist())
            scores = pipeline[-1].decision_function(x)
            pred, zero = labels_from_scores(scores), int((np.diff(x.indptr) == 0).sum())
        case_rows.append(pd.DataFrame({"case_id": suite["case_id"], "candidate": cid, "score": scores, "predicted": pred}))
        units = unit_outcomes(suite, pred)
        rng = np.random.default_rng(SEED)
        for (split, phenomenon), part in units.groupby(["split", "phenomenon"]):
            for ambiguity_filter in ("all", "low"):
                sub = part if ambiguity_filter == "all" else part[part["ambiguity"] == "low"]
                if sub.empty:
                    continue
                sub = sub.assign(failed=~sub["passed"])
                lo, hi = family_bootstrap(sub, "failed", rng)
                rows.append({"candidate": cid, "split": split, "phenomenon": phenomenon, "ambiguity": ambiguity_filter,
                             "families": sub["family_id"].nunique(), "units": len(sub),
                             "cases": int(sub["members"].sum()), "failed_units": int(sub["failed"].sum()),
                             "failure_rate": float(sub["failed"].mean()), "lo95": lo, "hi95": hi,
                             "zero_feature_cases": zero, "adjudication": "unadjudicated (provisional)"})
    OUT.mkdir(parents=True, exist_ok=True)
    result = pd.DataFrame(rows)
    result.to_csv(OUT / "failure_rates.csv", index=False, lineterminator="\n", float_format="%.6g")
    pd.concat(case_rows).to_csv(OUT / "case_predictions.csv", index=False, lineterminator="\n", float_format="%.17g")
    print(result[(result["split"] == "heldout") & (result["ambiguity"] == "all")]
          .pivot(index="candidate", columns="phenomenon", values="failure_rate").round(3))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("command", choices=["build", "evaluate"])
    {"build": build, "evaluate": evaluate}[parser.parse_args().command]()


if __name__ == "__main__":
    main()
